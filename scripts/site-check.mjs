#!/usr/bin/env node
// The site's coherence check. `--stamp` writes fingerprints; `--dist` also checks built Markdown output.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';
import { ROOT, DOCS, walk, pages, readLock, readSnapshot, resolveCitation, fingerprint } from './lib.mjs';

const stamp = process.argv.includes('--stamp');
const dist = process.argv.includes('--dist');
const errors = [];
const fail = (m) => errors.push(m);

const lock = readLock();
const snap = readSnapshot();
// @spec SITE-LINK-CHECK-002
if (snap.commit !== lock.commit) fail(`snapshot is at ${snap.commit}, the lock pins ${lock.commit}`);

// @spec SITE-LINK-CHECK-001
const siteIds = new Set();
for (const f of walk(join(ROOT, 'docs/intent'), (p) => p.endsWith('-specs.md')))
  for (const m of readFileSync(f, 'utf8').matchAll(/^- \[(?:x| |D)\] \*\*([A-Z0-9-]+)\*\*/gm)) siteIds.add(m[1]);
let annotations = 0;
for (const d of ['scripts', 'src', 'tests']) {
  for (const f of walk(join(ROOT, d), (p) => /\.(mjs|ts|astro|css)$/.test(p))) {
    for (const m of readFileSync(f, 'utf8').matchAll(/@spec ([A-Z0-9, -]+)/g)) {
      for (const id of m[1].split(',').map((s) => s.trim()).filter(Boolean)) {
        annotations++;
        if (!siteIds.has(id)) fail(`${relative(ROOT, f)}: @spec ${id} resolves to no site spec`);
      }
    }
  }
}

export const slugOf = (file) => relative(DOCS, file).replace(/\.mdx?$/, '').replace(/(^|\/)index$/, '');
const all = pages();
const slugs = new Set(all.map((p) => slugOf(p.file)));
const short = lock.commit.slice(0, 7);
let stamped = 0;

for (const p of all) {
  const lid = p.data.lid;
  // @spec SITE-CONT-FM-001
  if (!lid?.class) { fail(`${p.rel}: no lid.class`); continue; }
  const cites = lid.cites ?? [], docs = lid.docs ?? [];
  // @spec SITE-CONT-CLASS-001, SITE-CONT-CLASS-002
  if (lid.class === 'derived' && !cites.length) fail(`${p.rel}: derived page cites nothing`);
  if (lid.class === 'generated' && !/^\{\/\* Generated by /m.test(p.body)) fail(`${p.rel}: generated page lacks the generator comment`);
  // @spec SITE-LINK-CITE-003
  for (const c of cites) if (!resolveCitation(c, snap.specs).length) fail(`${p.rel}: citation ${c} resolves to no upstream requirement`);
  for (const d of docs) if (!snap.sections[d]) fail(`${p.rel}: design section ${d} is not in the snapshot`);
  // @spec SITE-LINK-FP-002, SITE-LINK-FP-003
  if (cites.length || docs.length) {
    const fp = fingerprint(lid, snap);
    if (lid.fingerprint !== fp) {
      if (stamp && lid.class !== 'generated') {
        let raw = p.raw.replace(/\n  fingerprint: .*/, '').replace(/\n  reviewed: .*/, '');
        raw = raw.replace(/^lid:\n/m, `lid:\n  reviewed: ${short}\n  fingerprint: ${fp}\n`);
        if (!raw.includes(`fingerprint: ${fp}`)) fail(`${p.rel}: cannot stamp; write lid as a block mapping`);
        else { writeFileSync(p.file, `---\n${raw}\n---\n${p.body}`); stamped++; }
      } else fail(`${p.rel}: fingerprint ${lid.fingerprint ?? '(none)'} differs from ${fp}; review the page, then run check --stamp`);
    }
  }
  // @spec SITE-CONT-VOL-001
  if (lid.class !== 'generated' && !p.data.legacy) {
    const m = p.body.match(/\b\d[\d,.]*\s?(?:×|x faster|x speed)/i);
    if (m) fail(`${p.rel}: multiplier claim "${m[0]}" on a current-version page`);
  }
  // @spec SITE-CONT-LINK-001
  const prose = p.body.replace(/```[\s\S]*?```/g, '');
  for (const m of prose.matchAll(/(?:\]\(|href=")(\/[^)"#\s]*)/g)) {
    const t = m[1].replace(/^\/|\/$/g, '');
    if (/\.(md|txt|svg|png|jpg|xml)$/.test(t)) continue;
    if (!slugs.has(t)) fail(`${p.rel}: link ${m[1]} points to no page`);
  }
}

// @spec SITE-MD-PAR-001, SITE-MD-PAR-002
if (dist) {
  const out = join(ROOT, 'dist');
  if (!existsSync(out)) fail('dist/ does not exist; run the build first');
  else for (const p of all) {
    const s = slugOf(p.file);
    const md = join(out, (s === '' ? 'index' : s) + '.md');
    if (!existsSync(md)) { fail(`${p.rel}: no Markdown output`); continue; }
    const text = readFileSync(md, 'utf8');
    for (const c of p.data.lid?.cites ?? []) if (!text.includes(c)) fail(`${p.rel}: Markdown output lacks citation ${c}`);
    if (/<\/?(Tabs|TabItem|Spec|Steps|Card|CardGrid|LinkCard|Aside)\b/.test(text.replace(/```[\s\S]*?```/g, ''))) fail(`${p.rel}: Markdown output contains a component tag`);
  }
}

if (errors.length) { console.error(errors.map((e) => `site-check: ${e}`).join('\n')); console.error(`site-check: FAILED with ${errors.length} problems`); process.exit(1); }
console.log(`site-check: OK: ${all.length} pages, ${annotations} @spec annotations, ${siteIds.size} site specs, upstream ${short}${stamp ? `, ${stamped} pages stamped` : ''}${dist ? ', Markdown parity checked' : ''}`);

#!/usr/bin/env node
// Writes the generated pages from an upstream checkout at the pinned commit.
//   node scripts/generate.mjs <upstream-dir>
// @spec SITE-GEN-RUN-001, SITE-GEN-RUN-002
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';
import YAML from 'yaml';
import { ROOT, DOCS, readLock, readSnapshot, status, resolveCitation, fingerprint } from './lib.mjs';

const dir = process.argv[2];
if (!dir) { console.error('usage: generate.mjs <upstream-dir>'); process.exit(2); }
const lock = readLock();
const head = execFileSync('git', ['-C', dir, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
if (head !== lock.commit) { console.error(`upstream checkout is at ${head}, the lock pins ${lock.commit}`); process.exit(1); }
const snap = readSnapshot();
const short = lock.commit.slice(0, 7);
const blob = (p) => `https://github.com/${lock.repo}/blob/${lock.commit}/${p}`;

function write(rel, fm, body) {
  const lid = { class: 'generated', cites: fm.cites ?? [], reviewed: short };
  lid.fingerprint = fingerprint(lid, snap);
  const front = { title: fm.title, description: fm.description, ...(fm.extra ?? {}), lid };
  const out = `---\n${YAML.stringify(front).trim()}\n---\n\n{/* Generated by scripts/generate.mjs from ${lock.repo}@${short}. Do not edit. */}\n\n${body.trim()}\n`;
  const file = join(DOCS, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, out);
  console.log(`generated ${rel}`);
}
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/\{/g, '&#123;');
const code = (s) => '`' + s + '`';

// ---- configuration reference -------------------------------------------------
// @spec SITE-GEN-CFG-001, SITE-GEN-CFG-002, SITE-GEN-CFG-003
const REGISTRY = 'spark/src/main/scala/io/indextables/spark/config/KeyRegistry.scala';
const GROUPS = {
  credentialsAndStorage: 'Credentials and storage', read: 'Reads and prewarm', writeAndIndexing: 'Writes and indexing',
  maintenance: 'Maintenance', companionSync: 'Companion sync', companionSlice14: 'Companion sources',
  nativeBoundary: 'Native library and memory', observability: 'Observability', transactionLog: 'Transaction log', cache: 'Caches',
};
export function parseRegistry(src) {
  const keys = [];
  const groupAt = [...src.matchAll(/private (?:val|def) (\w+): Seq\[KeySpec\]/g)].map((m) => ({ name: m[1], at: m.index }));
  const groupOf = (i) => groupAt.filter((g) => g.at < i).pop()?.name;
  for (const m of src.matchAll(/\b(k|fam)\(\s*(s?"[^"]*"(?:\s*\+\s*\w+)?)\s*,\s*/g)) {
    const group = groupOf(m.index);
    if (!GROUPS[group]) continue;
    // read the balanced argument list
    let i = m.index + m[1].length + 1, depth = 1, inStr = false;
    for (; i < src.length && depth; i++) {
      const c = src[i];
      if (c === '"' && src[i - 1] !== '\\') inStr = !inStr;
      else if (!inStr && c === '(') depth++;
      else if (!inStr && c === ')') depth--;
    }
    const args = src.slice(m.index + m[1].length + 1, i - 1);
    const tail = src.slice(i, i + 80);
    let name = m[2].replace(/^s?"/, '').replace(/"\s*\+\s*\w+$/, '<name>').replace(/"$/, '').replace(/\$\{?\w+\}?/g, '<name>');
    const rest = args.slice(m[2].length).replace(/^\s*,\s*/, '');
    const type = rest.match(/^(Enum\(Seq\(([^)]*)\)\)|\w+)/);
    const enumVals = type?.[2]?.match(/"[^"]*"/g)?.map((s) => s.slice(1, -1));
    const def = rest.match(/Some\("([^"]*)"\)/);
    const aliases = rest.match(/aliases = Seq\(([^)]*)\)/)?.[1].match(/"[^"]*"/g)?.map((s) => s.slice(1, -1)) ?? [];
    const bound = (k) => { const b = rest.match(new RegExp(`${k} = (One|Zero|MaxInt|Some\\(BigDecimal\\(([^)]*)\\)\\))`)); return b ? (b[1] === 'One' ? '1' : b[1] === 'Zero' ? '0' : b[1] === 'MaxInt' ? '2147483647' : b[2]) : null; };
    keys.push({
      group, name, family: m[1] === 'fam',
      type: enumVals ? enumVals.join(' \\| ') : type?.[1] === 'Policy' ? 'fallback \\| warn \\| refuse' : type?.[1] ?? '',
      default: def?.[1] ?? null, aliases, min: bound('min'), max: bound('max'),
      exclusive: /^\s*\.copy\(minExclusive = true/.test(tail),
      process: /processScoped = true/.test(rest),
    });
  }
  const noops = [];
  const nb = src.match(/private val noOps[\s\S]*?(?=\n  private val CredentialReason)/)?.[0] ?? '';
  for (const s of nb.matchAll(/s?"([^"]+)"/g)) noops.push(s[1].replace(/\$\{?\w+\}?/g, '<name>'));
  return { keys, noops };
}
const UNITS = { Size: 'size', DurationMs: 'ms', DurationSeconds: 'seconds', DurationHours: 'hours', Bool: 'boolean', Str: 'string', Int: 'integer', Long: 'integer', Double: 'number', ListOf: 'list', AutoOrInt: 'auto or integer' };
{
  const { keys, noops } = parseRegistry(readFileSync(join(dir, REGISTRY), 'utf8'));
  if (keys.length < 100) throw new Error(`only ${keys.length} keys parsed from the registry; its shape has changed`);
  let body = `Every configuration key the Spark binding accepts, read from the [key registry](${blob(REGISTRY)}) at upstream commit \`${short}\`. Defaults and keys are still changing upstream, so this page is regenerated on every sync and is the only place the site states a default.\n\n`;
  body += `Keys are case-insensitive and are shown relative to \`spark.indextables.\`. An option on the operation overrides a table property in the log, then the session configuration, then \`spark.indextables.*\` in the Hadoop configuration. Credentials and credential-steering keys cannot be table properties.\n\n`;
  body += `**Process-scoped** keys are read once per JVM, from the Spark configuration at start-up; a later different value is ignored with a warning. A key with no default shown is unset unless you set it.\n\n`;
  for (const [g, label] of Object.entries(GROUPS)) {
    const rows = keys.filter((k) => k.group === g);
    if (!rows.length) continue;
    body += `## ${label}\n\n| Key | Type | Default | Notes |\n|---|---|---|---|\n`;
    for (const k of rows) {
      const notes = [];
      if (k.family) notes.push('Prefix: every key under it');
      if (k.min !== null || k.max !== null) notes.push(`${k.min !== null ? `${k.exclusive ? '>' : '≥'} ${k.min}` : ''}${k.min !== null && k.max !== null ? ', ' : ''}${k.max !== null ? `≤ ${k.max}` : ''}`);
      if (k.process) notes.push('Process-scoped');
      if (k.aliases.length) notes.push(`Also ${k.aliases.map(code).join(', ')}`);
      body += `| ${code(k.name + (k.family ? '*' : ''))} | ${UNITS[k.type] ?? k.type} | ${k.default === null ? '' : code(k.default)} | ${esc(notes.join('. '))} |\n`;
    }
    body += '\n';
  }
  body += `## Accepted and ignored\n\nThese keys from IndexTables 0.5.x are accepted so that existing jobs keep running, and have no effect.\n\n${noops.map((n) => `- ${code(n.replace(/</g, '<').replace(/>/g, '>'))}`).join('\n')}\n`;
  write('reference/configuration.mdx', {
    title: 'Configuration reference', description: `All ${keys.length} configuration keys with types, defaults, ranges and aliases, generated from the key registry.`,
    cites: ['SPARK-CFG-KEY', 'SPARK-CFG-SRC', 'SPARK-CFG-VAL'], extra: { engine: ['spark'] },
  }, body);
}

// ---- availability matrix -------------------------------------------------------
// @spec SITE-GEN-AVAIL-001, SITE-GEN-AVAIL-002, SITE-GEN-AVAIL-003
{
  const areas = YAML.parse(readFileSync(join(ROOT, 'data/availability.yaml'), 'utf8'));
  const LABEL = { implemented: 'Available', gap: 'Planned', deferred: 'Deferred', planned: 'Planned' };
  const CLS = { implemented: 'available', gap: 'planned', deferred: 'deferred', planned: 'planned' };
  const ENG = { spark: 'Spark', datafusion: 'DataFusion' };
  const cites = new Set();
  let body = `What works today, by feature and engine. Each status is computed from the upstream requirements the row cites at commit \`${short}\`: a row is **Available** when its cited requirements are implemented, **Planned** when none is yet, and **Deferred** when all are deferred. Where a few requirements of an available feature are still open, the Limits column gives the count.\n\nIndexTables is at version \`0.1.0-SNAPSHOT\`. Performance measurements are not published yet; the benchmark grid is the remaining roadmap item.\n\n`;
  for (const a of areas) {
    body += `## ${a.area}\n\n| Feature | Engines | Status | Limits | Requirements |\n|---|---|---|---|---|\n`;
    for (const r of a.rows) {
      const ids = r.cites.flatMap((c) => { const x = resolveCitation(c, snap.specs); if (!x.length) throw new Error(`availability: ${c} resolves to nothing`); cites.add(c); return x; });
      const n = { implemented: 0, gap: 0, deferred: 0 };
      for (const id of ids) n[snap.specs[id].m]++;
      const st = r.force ?? (n.implemented ? 'implemented' : n.gap ? 'gap' : 'deferred');
      const open = n.gap && st === 'implemented' ? `${n.gap} of ${ids.length} requirements open` : '';
      r.note = [r.note, open].filter(Boolean).join('; ');
      body += `| [${esc(r.feature)}](${r.link}) | ${r.engine.map((e) => ENG[e]).join(', ')} | <span class="badge-s ${CLS[st]}">${LABEL[st]}</span> | ${esc(r.note ?? '')} | ${r.cites.map(code).join(' ')} |\n`;
    }
    body += '\n';
  }
  body += `## Not supported\n\n- HDFS storage.\n- Registering IndexTables tables in Unity Catalog or in a named Iceberg catalog. Use the table root with catalog-issued credentials instead.\n- A Structured Streaming sink.\n- Iceberg time travel for companions.\n- Writes through DataFusion.\n`;
  write('reference/availability.mdx', { title: 'Availability', description: 'What works today, by feature and engine, computed from the upstream requirements.', cites: [...cites].sort(), extra: { engine: ['spark', 'datafusion'] } }, body);
}

// ---- specification browser -------------------------------------------------------
// @spec SITE-GEN-SPEC-001, SITE-GEN-SPEC-002
{
  const byFile = {};
  for (const [id, s] of Object.entries(snap.specs)) {
    const f = (byFile[s.f] ??= { groups: {}, n: { implemented: 0, gap: 0, deferred: 0 } });
    const g = id.replace(/-\d+$/, '');
    (f.groups[g] ??= { implemented: 0, gap: 0, deferred: 0 })[s.m]++;
    f.n[s.m]++;
  }
  const tot = { implemented: 0, gap: 0, deferred: 0 };
  for (const f of Object.values(byFile)) for (const k of Object.keys(tot)) tot[k] += f.n[k];
  const ROOTS = { core: 'Core (engine-neutral)', spark: 'Spark binding', datafusion: 'DataFusion adapter' };
  let body = `IndexTables is built from written requirements. Each one has an ID, a test that cites it, and code that cites it. The documentation on this site cites the same IDs, so any statement here can be traced to the requirement it comes from.\n\nAt upstream commit \`${short}\` there are **${Object.keys(snap.specs).length.toLocaleString('en')} requirements**: ${tot.implemented.toLocaleString('en')} implemented, ${tot.gap} open and ${tot.deferred} deferred.\n\n`;
  for (const [root, label] of Object.entries(ROOTS)) {
    body += `## ${label}\n\n| Segment | Implemented | Open | Deferred | Requirement groups |\n|---|---|---|---|---|\n`;
    for (const [file, f] of Object.entries(byFile).filter(([p]) => p.startsWith(`docs/intent/${root}/`)).sort()) {
      const seg = file.split('/').at(-2);
      const groups = Object.entries(f.groups).map(([g, n]) => code(g) + (n.gap ? ` (${n.gap} open)` : '')).join(' ');
      body += `| [${seg}](${blob(file)}) | ${f.n.implemented} | ${f.n.gap} | ${f.n.deferred} | ${groups} |\n`;
    }
    body += '\n';
  }
  body += `## How to read a requirement ID\n\n\`SPARK-RD-IQ-004\` is requirement 4 of the IndexQuery group (\`IQ\`) in the read segment (\`RD\`) of the Spark binding. A page that cites \`SPARK-RD-IQ\` depends on every requirement in that group.\n`;
  write('reference/specifications.mdx', { title: 'Specifications', description: 'Every upstream requirement group, with counts of implemented, open and deferred requirements.', cites: [] }, body);
}
